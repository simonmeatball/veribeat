#!/usr/bin/env python3
"""Validate a Veribeat TXT chart and generate Vivado ROM inputs."""
import argparse
from pathlib import Path


def read_chart(source):
    metadata = {}
    notes = []
    last_time = -1
    seen = set()
    for line_number, raw in enumerate(source.read_text().splitlines(), 1):
        fields = raw.split('#', 1)[0].split()
        if not fields:
            continue
        prefix = f'{source}:{line_number}'
        if len(fields) != 2:
            raise ValueError(f'{prefix}: expected two fields')
        try:
            value = int(fields[1])
            if fields[0] in ('song_id', 'duration_ms', 'audio_offset_ms'):
                if fields[0] in metadata:
                    raise ValueError('duplicate metadata')
                metadata[fields[0]] = value
                continue
            timestamp = int(fields[0])
            if timestamp < 0 or timestamp < last_time:
                raise ValueError('times must be nonnegative and ordered')
            if value not in range(4):
                raise ValueError('lane must be 0, 1, 2, or 3')
            if (timestamp, value) in seen:
                raise ValueError('duplicate note')
            seen.add((timestamp, value))
            notes.append((timestamp, value))
            last_time = timestamp
            if len(notes) > 1024:
                raise ValueError('chart exceeds 1024 notes')
        except ValueError as error:
            raise ValueError(f'{prefix}: {error}') from error
    if set(metadata) != {'song_id', 'duration_ms', 'audio_offset_ms'}:
        raise ValueError('song_id, duration_ms, and audio_offset_ms are required')
    if not 0 <= metadata['song_id'] <= 9:
        raise ValueError('song_id must be 0 through 9')
    duration = metadata['duration_ms']
    offset = metadata['audio_offset_ms']
    if not 0 <= duration <= 0x7fff0000:
        raise ValueError('duration_ms is outside the supported range')
    adjusted = [(time + offset, lane) for time, lane in notes]
    if any(time < 0 or time > duration for time, lane in adjusted):
        raise ValueError('adjusted note times must fall within duration_ms')
    return metadata, adjusted


def memory_text(notes):
    words = [(1 << 39) | (time << 2) | lane for time, lane in notes]
    words.extend([0] * (1024 - len(words)))
    return ''.join(f'{word:010x}\n' for word in words)


def compile_chart(source, memory, config=None):
    metadata, notes = read_chart(source)
    memory.parent.mkdir(parents=True, exist_ok=True)
    memory.write_text(memory_text(notes))
    # Optional compatibility output for standalone callers.
    if config is not None:
        config.parent.mkdir(parents=True, exist_ok=True)
        config.write_text(
            '// Generated by tools/compile_chart.py. Edit the TXT source.\n'
            f'`define CHART_NOTE_COUNT {len(notes)}\n'
            f'`define CHART_SONG_ID {metadata["song_id"]}\n'
            f'`define CHART_DURATION_MS {metadata["duration_ms"]}\n'
        )
    return len(notes)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('chart', type=Path)
    parser.add_argument('--memory', type=Path, help='Defaults to the chart filename with a .mem extension')
    parser.add_argument('--config', type=Path, help='Optional standalone metadata header')
    args = parser.parse_args()
    try:
        memory = args.memory or args.chart.with_suffix('.mem')
        count = compile_chart(args.chart, memory, args.config)
    except (OSError, ValueError) as error:
        parser.exit(1, f'{error}\n')
    print(f'Compiled {count} notes into {memory}')


if __name__ == '__main__':
    main()
