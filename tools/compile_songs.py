#!/usr/bin/env python3
"""Compile all three menu songs and their shared metadata header."""
from pathlib import Path
import re
import tempfile
from compile_chart import compile_chart


def main():
    definitions = ['// Generated by tools/compile_songs.py. Edit charts/song_N.txt.']
    outputs = {}
    # Validate every chart before replacing any of the library's build inputs.
    with tempfile.TemporaryDirectory() as directory:
        staging = Path(directory)
        for song in range(3):
            stem = Path(f'charts/song_{song}')
            config_name = stem.with_name(stem.name + '_config.vh')
            config = staging / config_name.name
            memory = staging / stem.with_suffix('.mem').name
            count = compile_chart(stem.with_suffix('.txt'), memory, config)
            fields = dict(re.findall(r'^`define CHART_(\w+) (\d+)$', config.read_text(), re.MULTILINE))
            if int(fields['SONG_ID']) != song:
                raise ValueError(f'{stem}.txt must declare song_id {song}')
            for name in ('NOTE_COUNT', 'DURATION_MS'):
                definitions.append(f'`define SONG_{song}_{name} {fields[name]}')
            outputs[stem.with_suffix('.mem')] = memory.read_bytes()
            outputs[config_name] = config.read_bytes()
            print(f'Song {song}: {count} notes')
    outputs[Path('song_library_config.vh')] = ('\n'.join(definitions)+'\n').encode()
    for path, content in outputs.items():
        path.write_bytes(content)


if __name__ == '__main__':
    main()
