#!/usr/bin/env python3
"""Compile the three menu ROMs and their shared metadata header."""
from pathlib import Path
from compile_chart import memory_text, read_chart


def main():
    definitions = ['// Generated by tools/compile_songs.py. Edit charts/song_N.txt.']
    outputs = {}
    # Validate the whole library before replacing any build input.
    for song in range(3):
        source = Path(f'charts/song_{song}.txt')
        metadata, notes = read_chart(source)
        if metadata['song_id'] != song:
            raise ValueError(f'{source} must declare song_id {song}')
        definitions.append(f'`define SONG_{song}_NOTE_COUNT {len(notes)}')
        definitions.append(f'`define SONG_{song}_DURATION_MS {metadata["duration_ms"]}')
        outputs[source.with_suffix('.mem')] = memory_text(notes)
        print(f'Song {song}: {len(notes)} notes')
    outputs[Path('song_library_config.vh')] = '\n'.join(definitions)+'\n'
    for path, content in outputs.items():
        path.write_text(content)


if __name__ == '__main__':
    main()
